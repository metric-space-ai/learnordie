// Reproducible, data-only extraction. Never execute the source HTML/JavaScript.
// Usage: node scripts/import-model-original.mjs /directory/containing/originals
// Source file access stays behind the repository's Greppy navigation boundary.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { existsSync } from "node:fs";

if (process.argv.slice(2).some((arg) => arg === "--help" || arg === "-h")) {
  console.log("Usage: node scripts/import-model-original.mjs <original-source-directory>\nExtracts the eight authored slides and companion without executing source JavaScript.\nRequires Greppy and apply_patch; refuses to overwrite generated files.");
  process.exit(0);
}

const directory = process.argv[2];
if (!directory) throw new Error("Supply the directory containing the two original source files.");
const htmlName = "Modellbegriff_ThreeJS_clean.html";
const markdownName = "Der_Begriff_Modell_im_Wandel_der_Zeit_Vorlesungsunterlage.md";
const read = (name) => execFileSync("greppy", ["rg", "-N", "^", join(directory, name)], { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
const html = read(htmlName);
const markdown = read(markdownName);
const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const excerpt = html.match(/window\.MODELL_SLIDES = (\[[\s\S]*?\n\]);/)?.[1];
if (!excerpt) throw new Error("Original slide data boundary not found.");
const expected = ["nav", "kicker", "title", "lead", "formula", "takeaway", "question", "scene", "sceneTitle", "sceneSub", "accent", "source", "notes"];
const slides = [...excerpt.matchAll(/\{([\s\S]*?)\n  \}/g)].map((match) => {
  let remaining = match[1];
  const result = {};
  const property = /\s*(\w+):(?:'([^'\\]*)'|`([^`\\]*)`)\s*,?/y;
  let offset = 0;
  while (offset < remaining.trimEnd().length) {
    property.lastIndex = offset;
    const field = property.exec(remaining);
    if (!field || Object.hasOwn(result, field[1])) throw new Error("Unsupported or duplicate source syntax; review the original.");
    result[field[1]] = field[2] ?? field[3];
    offset = property.lastIndex;
  }
  if (JSON.stringify(Object.keys(result)) !== JSON.stringify(expected)) throw new Error("Source field inventory changed.");
  return result;
});
if (slides.length !== 8) throw new Error("Expected the eight-part authoritative presentation.");
const sourcesHtml = html.match(/const sourceHTML=`([\s\S]*?)`;/)?.[1];
if (!sourcesHtml) throw new Error("Source reference dialog not found.");
const sections = [...markdown.matchAll(/^## (.+)$/gm)].map((match, index, matches) => ({
  title: match[1], startLine: markdown.slice(0, match.index).split("\n").length,
  text: markdown.slice(match.index, matches[index + 1]?.index ?? markdown.length)
}));
const provenance = {
  html: { file: htmlName, sha256: sha256(html), authoredDataSha256: sha256(excerpt), sourceDialogSha256: sha256(sourcesHtml) },
  companion: { file: markdownName, sha256: sha256(markdown), lines: markdown.trimEnd().split("\n").length },
  authority: "Scene-port header: packages/slide-engine/src/scenes/modell-factories.ts; companion explicitly names the clean HTML as its presentation.",
  fieldsPerSlide: expected,
  sections: sections.map(({ title, startLine, text }) => ({ title, startLine, sha256: sha256(text) }))
};
const files = {
  "src/lib/model-original-source.ts": `// Generated by scripts/import-model-original.mjs. Author text, not new examples.\nexport const originalModelSlides = ${JSON.stringify(slides, null, 2)} as const;\nexport const originalModelSourcesHtml = ${JSON.stringify(sourcesHtml)};\nexport const originalModelCompanion = ${JSON.stringify(markdown)};\nexport const originalModelProvenance = ${JSON.stringify(provenance, null, 2)} as const;\n`,
  "docs/sources/model-original/authored-slides.txt": excerpt + "\n",
  "docs/sources/model-original/source-dialog.html": sourcesHtml + "\n",
  [`docs/sources/model-original/${markdownName}`]: markdown,
  "docs/sources/model-original/provenance.json": JSON.stringify(provenance, null, 2) + "\n"
};
// Use apply_patch for local file creation; this importer refuses overwrites.
for (const path of Object.keys(files)) if (existsSync(path)) throw new Error(`Refusing to overwrite ${path}; extract into a clean review worktree.`);
const patch = "*** Begin Patch\n" + Object.entries(files).map(([path, body]) => `*** Add File: ${path}\n${body.trimEnd().split("\n").map((line) => "+" + line).join("\n")}\n`).join("") + "*** End Patch\n";
execFileSync("apply_patch", [patch], { stdio: "inherit" });
console.log(JSON.stringify({ slides: slides.length, fields: expected.length, companionSections: sections.length, provenance }, null, 2));
